package kee.ram;

public class operations {
	public static void main(String[]args) {
		int a=10;
		int b=30;
		int add=a+b;
		int sub=a-b;
		int mult=a*b;
		int div=a/b;
		System.out.println("Addition of "+a+" and "+b+" is:"+add);
		System.out.println("Subtraction of "+a+" "+b+" is:"+sub);
		System.out.println("Multiplication of "+a+" "+b+" is:"+mult);
		System.out.println("Division of "+a+" "+b+" is:"+div);
	}

}
